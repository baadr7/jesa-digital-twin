@models_present
def test_a1_initialization():
    p = A1Predictor()
    assert p.model is not None, "A1 binary model failed to load"
    assert "AirTemp_K" in p.state
    assert "ToolWear_min" in p.state


@models_present
def test_a1_predict_normal():
    """Normal operating conditions → low failure probability."""
    p = A1Predictor()
    p.state.update({"AirTemp_K": 298.0, "ProcTemp_K": 308.0,
                    "Speed_rpm": 1500.0, "Torque_Nm": 40.0, "ToolWear_min": 10.0})
    res = p.predict()
    assert res is not None
    assert "machine_failure" in res
    assert "failure_probability" in res
    assert 0.0 <= res["failure_probability"] <= 1.0
    assert res["machine_failure"] in (0, 1)


@models_present
def test_a1_predict_high_wear():
    """High tool wear should produce higher failure probability."""
    p = A1Predictor()
    p.state.update({"AirTemp_K": 298.0, "ProcTemp_K": 308.0,
                    "Speed_rpm": 1500.0, "Torque_Nm": 60.0, "ToolWear_min": 230.0})
    res = p.predict()
    assert res is not None
    assert res["failure_probability"] >= 0.0


@models_present
def test_a1_per_mode_predictions():
    """Per-mode predictions dict is populated when models are loaded."""
    p = A1Predictor()
    if not p.mode_models:
        pytest.skip("Per-mode models not found")
    p.state.update({"AirTemp_K": 298.0, "ProcTemp_K": 308.0,
                    "Speed_rpm": 1500.0, "Torque_Nm": 40.0, "ToolWear_min": 10.0})
    res = p.predict()
    assert res is not None
    assert "mode_predictions" in res
    assert "mode_probabilities" in res
    for mode in p.mode_models:
        assert mode in res["mode_predictions"]
        assert res["mode_predictions"][mode] in (0, 1)
        assert 0.0 <= res["mode_probabilities"][mode] <= 1.0


