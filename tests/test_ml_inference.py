@a3_models_present
def test_a3_predict_requires_history():
    """predict() is only called when history >= AE_SEQ_LEN; with fewer rows
    the update() timer guard prevents calling predict() directly, but
    predict() itself works with any non-empty history using Isolation Forest alone.
    This test verifies the result structure when called with minimal history."""
    p = A3Predictor()
    # Only 5 rows — Isolation Forest can still score, AE won't contribute
    for _ in range(5):
        p.history.append({c: 0.5 for c in p.raw_cols})
    result = p.predict()
    # IF scores even with partial history; result should be a valid dict or None
    if result is not None:
        assert "anomaly_score" in result
        assert "is_anomaly" in result


@a3_models_present
def test_a3_predict_full():
    """predict() returns valid anomaly score with sufficient history."""
    p = A3Predictor()
    # Fill 20 rows of normal-ish values
    for _ in range(20):
        p.history.append({
            "TP2": 8.5, "TP3": 10.2, "H1": 7.8,
            "DV_pressure": 9.1, "Reservoirs": 8.9,
            "Oil_temperature": 55.0, "Motor_current": 7.2,
            "COMP": 1.0,
        })
    result = p.predict()
    assert result is not None
    assert "anomaly_score" in result
    assert "is_anomaly"    in result
    assert isinstance(result["anomaly_score"], float)
    assert result["is_anomaly"] in (0, 1)


